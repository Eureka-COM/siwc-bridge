// Copy the shared connection core from the SDK (repository root) into this
// integration before every build, typecheck and test. The SDK sources are the
// only place authentication, Windows storage, HTTP limits and errors are edited;
// src/core/ is generated and not committed.
import { mkdir, readFile, writeFile, rm } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const integration = join(here, '..');
const sdk = join(integration, '..', '..');
const target = join(integration, 'src', 'core');
const modules = ['app', 'auth', 'errors', 'http', 'store'];
const banner = '// GENERATED by scripts/sync-core.mjs from the SDK source. Do not edit; edit the repository root src/ instead.\n';

await rm(target, { recursive: true, force: true });
await mkdir(target, { recursive: true });
for (const name of modules) {
  let source = await readFile(join(sdk, 'src', `${name}.ts`), 'utf8');
  if (name === 'store') {
    // One directory deeper: lib/core/store.js → scripts/dpapi.ps1.
    const from = "new URL('../scripts/dpapi.ps1', import.meta.url)";
    if (source.split(from).length !== 2) throw new Error('sync-core: SDK store.ts no longer has the expected DPAPI helper path.');
    source = source.replace(from, "new URL('../../scripts/dpapi.ps1', import.meta.url)");
  }
  await writeFile(join(target, `${name}.ts`), banner + source, 'utf8');
}
// The DPAPI helper is shipped with this package, identical to the SDK's.
await writeFile(join(integration, 'scripts', 'dpapi.ps1'), await readFile(join(sdk, 'scripts', 'dpapi.ps1')));
